def normalize_course_code(code: str) -> str:
    normalized = "".join(ch for ch in str(code or "") if ch.isdigit()).zfill(5)
    return LEGACY_COURSE_CODE_ALIASES.get(normalized, normalized)


def infer_subject_category(code: str, name: str) -> str:
    if code in {"15040", "15041", "15042", "15043", "15044"}:
        return "public"
    if any(token in name for token in ("法", "刑", "民", "诉讼", "宪", "合同", "公司")):
        return "law"
    if any(token in name for token in ("护理", "药", "医学", "卫生", "细胞", "化学")):
        return "medicine"
    if any(token in name for token in ("计算机", "数据", "软件", "网络", "程序", "电子", "信号", "控制")):
        return "computer"
    if any(token in name for token in ("教育", "学前", "幼儿", "小学", "课程", "教学", "教师")):
        return "education"
    if any(token in name for token in ("英语", "文学", "汉语", "语言", "写作")):
        return "language"
    if any(token in name for token in ("设计", "艺术", "美学", "动漫")):
        return "design"
    if any(token in name for token in ("会计", "财务", "经济", "金融", "贸易", "营销", "商务", "管理")):
        return "economics_management"
    if any(token in name for token in ("工程", "结构", "施工", "机械", "力学", "测量", "土力学", "混凝土", "钢结构")):
        return "engineering"
    if any(token in name for token in ("公安", "警察", "罪犯", "狱")):
        return "public_security"
    return "professional"


def build_subject_seed_data() -> List[Dict[str, object]]:
    old_codes_by_current: Dict[str, List[str]] = {}
    for old_code, current_code in LEGACY_COURSE_CODE_ALIASES.items():
        old_codes_by_current.setdefault(current_code, []).append(old_code)

    return [
        {
            "code": code,
            "old_codes": old_codes_by_current.get(code, []),
            "name": name,
            "category": infer_subject_category(code, name),
            "description": f"{CATALOG_SOURCE}收录课程。课程代码 {code}，请以教育考试院及各省考试院发布的最新安排为准。",
            "exam_duration": 150,
            "total_score": 100,
        }
        for code, name in NATIONAL_SELF_EXAM_COURSES_2026
    ]
